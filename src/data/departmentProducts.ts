// Convert each DepartmentProduct to the platform's rich Product object
export function convertDepartmentProductToProduct(item: DepartmentProduct): Product {
  const meta = DEPARTMENT_TO_CATEGORY_MAP[item.department] || { categoryId: 'cat-general', nameAr: item.department };
  const numMoq = parseInt(item.moq.replace(/[^0-9]/g, ''), 10) || 10;
  const unit = item.moq.replace(/[0-9\s]/g, '') || 'Pieces';

  return {
    id: item.id,
    name: item.name,
    titleEn: item.name,
    titleAr: item.name,
    categoryId: meta.categoryId,
    department: item.department,
    brand: item.vendor,
    vendor: item.vendor,
    price: item.price,
    currency: 'SAR',
    moq: numMoq,
    unit: unit,
    stock: 500,
    image: item.image,
    images: [item.image],
    descriptionEn: `${item.name} supplied directly by ${item.vendor}. Certified commercial quality with verified testing. Minimum order quantity: ${item.moq}.`,
    descriptionAr: `${item.name} مقدم من ${item.vendor}. منتج موثوق بجودة تجارية عالية معتمد ومعاين للمبيعات بالجملة. الحد الأدنى للطلب: ${item.moq}.`,
    specs: {
      'Department': item.department,
      'Vendor': item.vendor,
      'Min Order (MOQ)': item.moq,
      'Price': `${item.price} SAR`,
      'Rating': `${item.rating} / 5.0`,
      'Origin': 'Verified Atlas Supplier',
    },
    isFeatured: true,
    rating: item.rating,
    ordersCount: Math.floor(item.rating * 50) + 120,
    createdAt: '2026-03-01',
    badge: item.rating >= 4.8 ? 'Best Seller' : 'Verified',
    badgeAr: item.rating >= 4.8 ? 'الأكثر طلباً' : 'موثق',
  };
}

